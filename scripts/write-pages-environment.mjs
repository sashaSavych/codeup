/**
 * Writes src/environments/environment.pages.ts from process.env (GitHub Actions secrets).
 * Run before: npx ng build --configuration=github-pages --base-href=/REPO/
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const out = join(root, 'src/environments/environment.pages.ts');

const supabaseUrl = process.env.SUPABASE_URL ?? '';
const supabasePublishableKey = process.env.SUPABASE_PUBLISHABLE_KEY ?? '';
const chatAiEndpoint = process.env.CHAT_AI_ENDPOINT ?? '';

const src = `/* Generated by scripts/write-pages-environment.mjs — not committed with secrets. */
export const environment = {
  production: true,
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabasePublishableKey: ${JSON.stringify(supabasePublishableKey)},
  chatAiEndpoint: ${JSON.stringify(chatAiEndpoint)} as string | undefined,
};
`;

writeFileSync(out, src, 'utf8');
console.log('Wrote', out);
